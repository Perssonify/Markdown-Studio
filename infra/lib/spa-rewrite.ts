import { readdirSync } from "node:fs";
import { join, relative, sep } from "node:path";

/**
 * Vercel serves a request in two steps: a file that exists is served as is,
 * and only otherwise does the rewrite apply (so /sw.js is the worker, /about
 * is index.html, and a missing /assets/x.js is a 404 because the rewrite
 * excludes /assets/). S3 behind CloudFront has no "does the file exist" step,
 * so the CloudFront Function carries the list of files the build produced.
 *
 * `/assets/*` is a separate behaviour that never runs this function, so its
 * (many, hashed) files are not listed.
 */
export function siteFiles(distDir: string): string[] {
  const out: string[] = [];
  const walk = (dir: string) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else out.push("/" + relative(distDir, p).split(sep).join("/"));
    }
  };
  walk(distDir);
  return out.filter((f) => !f.startsWith("/assets/") && !f.endsWith(".map")).sort();
}

/** The CloudFront Function (cloudfront-js-2.0) for the default behaviour. */
export function rewriteFunctionCode({ files, source, destination }: { files: string[]; source: string; destination: string }): string {
  const table: Record<string, 1> = {};
  for (const f of files) table[f] = 1;
  return [
    "// Generated by infra/lib/spa-rewrite.ts from apps/web/vercel.json and the built files.",
    `var FILES = ${JSON.stringify(table)};`,
    `var REWRITE = new RegExp(${JSON.stringify(`^${source}$`)});`,
    "function handler(event) {",
    "  var request = event.request;",
    `  if (FILES[request.uri] !== 1 && REWRITE.test(request.uri)) request.uri = ${JSON.stringify(destination)};`,
    "  return request;",
    "}",
  ].join("\n");
}
